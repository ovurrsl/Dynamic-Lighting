/**
 * Looks a key up, falling back to English and finally to the key itself. The
 * last fallback is unreachable while `en` is the type's source, and it is here
 * so a future key added at runtime cannot render as `undefined`.
 */
export function translate (locale: Locale, key: MessageKey, values?: Record<string, string | number>): string {
  const text = TABLES[locale]?.[key] ?? TABLES[FALLBACK_LOCALE]?.[key] ?? key
  if (values === undefined) return text
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => {
    const value = values[name]
    if (value === undefined) return whole
    // A reason, a problem or an error is a sentence that came OUT of the
    // engine or the storage layer, in English; if it is one of ours it is said
    // in this language (lib/i18n/engine-text.ts). Only these three names, so a
    // strip somebody named after an error message stays what they typed.
    if (typeof value === 'string' && ENGINE_TEXT_VALUES.has(name)) {
      return localiseEngineText(value, (k, v) => translate(locale, k, v))
    }
    return String(value)
  })
}

const ENGINE_TEXT_VALUES: ReadonlySet<string> = new Set(['reason', 'problem', 'error'])

/**
 * Whether a language carries its own string for a key, as opposed to borrowing
 * English for it. Distinct from comparing `translate` output against English,
 * because translations legitimately coincide - German's '{count} LEDs' is the
 * German string AND identical to the English one.
 */
export function has (locale: Locale, key: MessageKey): boolean {
  return TABLES[locale]?.[key] !== undefined
}

/** How much of a language is done, for the picker to be honest about it. */
export function completeness (locale: Locale): number {
  const total = Object.keys(en).length
  return Math.round((Object.keys(TABLES[locale] ?? {}).length / total) * 100)
}
